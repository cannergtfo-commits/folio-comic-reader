STAR2 = star(77.5, 46, 3)
GOLD = [("0", "#F3DFAE"), ("0.55", "#D8B676"), ("1", "#A9844A")]

def svg(full=True, size=512, box="0 0 108 108"):
    stops = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in GOLD)
    bg = ('<rect width="108" height="108" fill="url(#bg)"/><circle cx="54" cy="52" r="34" fill="url(#halo)"/>' if full else "")
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}" width="{size}" height="{size}"><defs>
<radialGradient id="bg" cx="54" cy="44" r="78" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#2A241C"/><stop offset="1" stop-color="#0A0908"/></radialGradient>
<radialGradient id="halo" cx="54" cy="52" r="34" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#C9A96E" stop-opacity="0.22"/><stop offset="1" stop-color="#C9A96E" stop-opacity="0"/></radialGradient>
<linearGradient id="gold" x1="36" y1="28" x2="74" y2="80" gradientUnits="userSpaceOnUse">{stops}</linearGradient>
<linearGradient id="back" x1="36" y1="28" x2="74" y2="80" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#8E7244"/><stop offset="1" stop-color="#4E3D22"/></linearGradient></defs>
{bg}<path d="{BACK}" fill="url(#back)" transform="rotate(9 58 54)"/>
<g transform="rotate(-6 52 54)"><path d="{PAGE}" fill="url(#gold)"/><path d="{P1} {P2} {P3}" fill="#16130F"/>
<path d="{MOON}" fill="#E9CF96"/><path d="{BUBBLE}" fill="none" stroke="#C9A96E" stroke-width="0.9" stroke-linejoin="round"/>
<path d="{SPEED}" stroke="#C9A96E" stroke-opacity="0.85" stroke-width="0.9" stroke-linecap="round"/></g>
<path d="{STAR1}" fill="#FFF1CC"/><path d="{STAR2}" fill="#E9CF96"/></svg>'''

def grad(kind, **kw):
    attrs = " ".join(f'android:{k}="{v}"' for k, v in kw.items())
    return f'<aapt:attr name="android:fillColor"><gradient android:type="{kind}" {attrs}/></aapt:attr>'

def gold_grad():
    items = "".join(f'<item android:offset="{o}" android:color="#FF{c[1:]}"/>' for o, c in GOLD)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="36" android:startY="28" '
            f'android:endX="74" android:endY="80">{items}</gradient></aapt:attr>')

HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by folio-icon/gen.py (source: tools/icon/). -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="{w}dp" android:height="{w}dp" android:viewportWidth="108" android:viewportHeight="108">\n')

