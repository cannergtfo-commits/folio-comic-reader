def kf(prop, frames, dur, interp="@android:interpolator/fast_out_slow_in"):
    ks = "".join(f'<keyframe android:fraction="{f}" android:value="{v}"/>' for f, v in frames)
    return (f'<objectAnimator android:duration="{dur}" android:interpolator="{interp}">'
            f'<propertyValuesHolder android:propertyName="{prop}" android:valueType="floatType">{ks}</propertyValuesHolder></objectAnimator>')

def target(name, *anims):
    return (f'    <target android:name="{name}"><aapt:attr name="android:animation"><set>' + "".join(anims) +
            '</set></aapt:attr></target>\n')

SPLASH_MS = 900
splash_anim = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icon/gen.py: the splash icon assembles itself. -->\n'
    '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">\n'
    '    <aapt:attr name="android:drawable">\n' + HEAD.format(w=240).split("\n", 2)[2] + splash_body() + "</vector>\n    </aapt:attr>\n"
    + target("back", kf("rotation", [(0, -6), (0.25, -6), (0.75, 11), (1, 9)], SPLASH_MS))
    + target("lift", kf("scaleX", [(0, 0.78), (0.55, 1.04), (1, 1)], SPLASH_MS), kf("scaleY", [(0, 0.78), (0.55, 1.04), (1, 1)], SPLASH_MS),
             kf("translateY", [(0, 7), (0.6, -1), (1, 0)], SPLASH_MS))
    + target("star1", kf("scaleX", [(0, 0), (0.45, 0), (0.8, 1.25), (1, 1)], SPLASH_MS), kf("scaleY", [(0, 0), (0.45, 0), (0.8, 1.25), (1, 1)], SPLASH_MS),
             kf("rotation", [(0, -90), (0.45, -90), (1, 0)], SPLASH_MS))
    + target("star2", kf("scaleX", [(0, 0), (0.62, 0), (0.9, 1.35), (1, 1)], SPLASH_MS), kf("scaleY", [(0, 0), (0.62, 0), (0.9, 1.35), (1, 1)], SPLASH_MS))
    + "</animated-vector>\n")
open(os.path.join(RES, "ic_splash_anim.xml"), "w").write(splash_anim)

