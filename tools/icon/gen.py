"""Generates Folio's adaptive icon VectorDrawables + store PNG from one geometry spec."""
import os
import cairosvg  # pip install cairosvg
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "app", "src", "main", "res", "drawable")

def rr(x, y, w, h, r):
    return (f"M{x+r:.2f},{y:.2f} H{x+w-r:.2f} A{r},{r} 0 0 1 {x+w:.2f},{y+r:.2f} V{y+h-r:.2f} "
            f"A{r},{r} 0 0 1 {x+w-r:.2f},{y+h:.2f} H{x+r:.2f} A{r},{r} 0 0 1 {x:.2f},{y+h-r:.2f} "
            f"V{y+r:.2f} A{r},{r} 0 0 1 {x+r:.2f},{y:.2f} Z")

def star(cx, cy, r, k=0.12):
    a = r * k
    return (f"M{cx},{cy-r} Q{cx+a},{cy-a} {cx+r},{cy} Q{cx+a},{cy+a} {cx},{cy+r} "
            f"Q{cx-a},{cy+a} {cx-r},{cy} Q{cx-a},{cy-a} {cx},{cy-r} Z")

BACK = rr(41, 31, 34, 46, 2.6)
PAGE = rr(34, 30, 36, 48, 2.8)
P1 = rr(37.2, 33.2, 29.6, 19.6, 1.1)
P2 = rr(37.2, 55.4, 13.4, 19.4, 1.1)
P3 = rr(53.2, 55.4, 13.6, 19.4, 1.1)
MOON = "M46,38.2 A5.6,5.6 0 1 0 51.2,46.8 A4.6,4.6 0 1 1 46,38.2 Z"
